#!/usr/bin/env sh
# SPDX-License-Identifier: Apache-2.0
set -eu

# PROTOTYPE ONLY. Vendors `substrait-antlr` into `vendor/substrait-antlr` with
# the type grammar regenerated using ANTLR's `-visitor` flag, which the
# published crate does not pass. Everything else matches the published crate:
# the same forked ANTLR JAR and the same grammar tag.
#
# If this approach is adopted, the flag belongs in substrait-packaging's
# `generate_antlr.sh` and this script and the vendored crate go away.
#
# Requires curl, java and git. SUBSTRAIT_HOME must point at a clone of
# substrait-io/substrait (defaults to ../substrait).

VERSION="0.102.0"
SUBSTRAIT_HOME="${SUBSTRAIT_HOME:-../substrait}"
ANTLR_URL="https://github.com/antlr4rust/antlr4/releases/download/v0.5.0/antlr4-4.13.3-SNAPSHOT-complete.jar"
ANTLR_SHA256="8227a91d45625aec824e31cc7792ecb8b22b973da71f2396e81542b88d897d8f"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$ROOT/vendor/substrait-antlr"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

curl -fsSL -o "$WORK/crate.tar.gz" "https://crates.io/api/v1/crates/substrait-antlr/$VERSION/download"
tar -xzf "$WORK/crate.tar.gz" -C "$WORK"
CRATE="$WORK/substrait-antlr-$VERSION"

curl -fsSL -o "$WORK/antlr.jar" "$ANTLR_URL"
echo "$ANTLR_SHA256  $WORK/antlr.jar" | shasum -a 256 -c - >/dev/null

mkdir -p "$WORK/grammar"
for grammar in SubstraitLexer SubstraitType; do
    git -C "$SUBSTRAIT_HOME" show "v$VERSION:grammar/$grammar.g4" > "$WORK/grammar/$grammar.g4"
done
(cd "$WORK/grammar" && java -jar "$WORK/antlr.jar" -Dlanguage=Rust -visitor SubstraitLexer.g4 SubstraitType.g4)

TYPE_DIR="$CRATE/src/substrait_type"
rm -f "$TYPE_DIR"/*.rs
for generated in "$WORK"/grammar/*.rs; do
    {
        printf '// SPDX-License-Identifier: Apache-2.0\n#![allow(clippy::all)]\n#![allow(unused_parens)]\n#![cfg_attr(rustfmt, rustfmt_skip)]\n'
        cat "$generated"
    } > "$TYPE_DIR/$(basename "$generated")"
done
{
    printf '// SPDX-License-Identifier: Apache-2.0\n\n'
    printf '//! Generated ANTLR lexer, parser, listeners and visitors for the Substrait type grammar.\n\n'
    for module in "$TYPE_DIR"/*.rs; do
        name="$(basename "$module" .rs)"
        [ "$name" = "mod" ] || printf 'pub mod %s;\n' "$name"
    done
    printf '\npub use substraittypelexer::SubstraitTypeLexer;\n'
    printf 'pub use substraittypeparser::SubstraitTypeParser;\n'
} > "$TYPE_DIR/mod.rs"

rm -rf "$VENDOR"
mkdir -p "$VENDOR"
cp -R "$CRATE/src" "$VENDOR/src"
cat > "$VENDOR/Cargo.toml" <<EOF
# SPDX-License-Identifier: Apache-2.0
# Generated by scripts/vendor-substrait-antlr-visitor.sh. Do not edit.
[package]
name = "substrait-antlr"
version = "$VERSION"
edition = "2021"
license = "Apache-2.0"
publish = false

[dependencies]
antlr4rust = "0.5.2"
EOF
